// Original drawing coordinates. Each brush is a filled, tapered ribbon sampled from
// cubic Bezier spines, not a constant-width SVG stroke with rounded tube ends.
const point = (a, b, c, d, t) => (1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t ** 2 * c + t ** 3 * d
const tangent = (a, b, c, d, t) => 3 * (1 - t) ** 2 * (b - a) + 6 * (1 - t) * t * (c - b) + 3 * t ** 2 * (d - c)

export function brush(segments, width = 8, phase = 0) {
  const left = [], right = []
  segments.forEach((s, segment) => {
    for (let step = 0; step <= 32; step++) {
      const t = step / 32
      const progress = (segment + t) / segments.length
      const x = point(s[0], s[2], s[4], s[6], t)
      const y = point(s[1], s[3], s[5], s[7], t)
      const dx = tangent(s[0], s[2], s[4], s[6], t)
      const dy = tangent(s[1], s[3], s[5], s[7], t)
      const length = Math.hypot(dx, dy) || 1
      const taper = Math.sin(Math.PI * progress) ** .42
      const pressure = .8 + .17 * Math.sin(progress * 18 + phase) + .07 * Math.sin(progress * 53)
      const radius = Math.max(.15, width * taper * pressure / 2)
      left.push(`${(x - dy / length * radius).toFixed(1)},${(y + dx / length * radius).toFixed(1)}`)
      right.push(`${(x + dy / length * radius).toFixed(1)},${(y - dx / length * radius).toFixed(1)}`)
    }
  })
  return `M${left.join('L')}L${right.reverse().join('L')}Z`
}

